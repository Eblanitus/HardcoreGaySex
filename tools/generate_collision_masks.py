#!/usr/bin/env python3
"""Bake alpha > 128 into GPU-independent collision masks. Requires Pillow 11.3.0."""
import argparse
import base64
import hashlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'FrostMelee/Content/WeaponCollisionMasks.Generated.cs'
SPRITES = (
    ('IceSickle', 'IceSpearHeld'),
    ('IceBlade', 'Ice_Blade'),
    ('Frostbrand', 'Frostbrand'),
    ('Frozen', 'IceSpearFrozen'),
)


def pack_alpha(image):
    alpha = image.convert('RGBA').getchannel('A').tobytes()
    packed = bytearray((len(alpha) + 7) // 8)
    for i, value in enumerate(alpha):
        if value > 128:
            packed[i // 8] |= 1 << (i % 8)
    return bytes(packed)


def render():
    entries = []
    for name, filename in SPRITES:
        path = ROOT / f'FrostMelee/Items/{filename}.png'
        with Image.open(path) as image:
            width, height = image.size
            packed = pack_alpha(image)
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        encoded = base64.b64encode(packed).decode('ascii')
        entries.append(f'''        // Items/{filename}.png SHA256: {digest}
        internal static readonly Mask {name} = new Mask({width}, {height},
            "{encoded}");''')
    return '''// <auto-generated>tools/generate_collision_masks.py; do not edit by hand.</auto-generated>
using System;
using Terraria.ID;

namespace FrostMelee.Content
{
    // Shared gameplay data, not client TextureAssets. Resource packs cannot change reach.
    internal static class WeaponCollisionMasks
    {
        internal sealed class Mask
        {
            internal readonly int Width, Height;
            private readonly byte[] bits;

            internal Mask(int width, int height, string encoded)
            {
                Width = width;
                Height = height;
                bits = Convert.FromBase64String(encoded);
                if (bits.Length != (width * height + 7) / 8)
                    throw new ArgumentException("Invalid weapon collision mask size.");
            }

            internal bool IsSolid(int x, int y)
            {
                int index = y * Width + x;
                return (bits[index / 8] & (1 << (index % 8))) != 0;
            }
        }

''' + '\n\n'.join(entries) + '''

        internal static Mask Get(int itemType) => itemType switch
        {
            ItemID.IceSickle => IceSickle,
            ItemID.IceBlade => IceBlade,
            ItemID.Frostbrand => Frostbrand,
            _ => null
        };
    }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated data is stale')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.exit(1, 'Collision masks are stale; run tools/generate_collision_masks.py\n')
        print('Collision masks match source PNGs.')
    else:
        OUTPUT.write_text(content)
        print(f'Generated {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
